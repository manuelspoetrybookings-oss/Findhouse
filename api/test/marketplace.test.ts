import {it,expect} from 'vitest';
import {generateKeyPair,SignJWT} from 'jose';
import {createApp} from '../src/index';import {makeD1} from './helpers/d1';
it('restricts edits and deletion to owner/admin, counts likes once, and hides deleted discussions',async()=>{
 const {publicKey,privateKey}=await generateKeyPair('RS256'),{d1,db}=makeD1(),app=createApp(()=>publicKey);
 const env={DB:d1,ENVIRONMENT:'production',CLERK_ISSUER:'https://clerk.example',CLERK_JWKS_URL:'unused',ALLOWED_ORIGINS:'https://rentarapp.vercel.app'} as any;
 const tokens=await Promise.all(['owner','reader','admin'].map(sub=>new SignJWT({azp:env.ALLOWED_ORIGINS,email:'manuelspoetry.bookings@gmail.com',role:'admin'}).setProtectedHeader({alg:'RS256'}).setIssuer(env.CLERK_ISSUER).setSubject(sub).setIssuedAt().setExpirationTime('5m').sign(privateKey)));
 const req=(path:string,method='GET',who=0,body?:unknown)=>app.request('/v1'+path,{method,headers:{Authorization:'Bearer '+tokens[who],'Content-Type':'application/json'},...(body!==undefined?{body:JSON.stringify(body)}:{})},env);
 const users:any[]=[];for(let i=0;i<3;i++)users.push(await (await req('/me','GET',i)).json());
 db.prepare("UPDATE users SET role='admin' WHERE id=?").run(users[2].id);
 const data={title:'Inspect my apartment',area:'Lekki',details:'Check water and electricity',budget:5000};
 const created:any=await (await req('/community/inspections','POST',0,data)).json(),p='/community/inspections/'+created.id;
 expect((await req(p,'PATCH',1,{...data,action:'edit',title:'Stolen'})).status).toBe(409);
 expect((await req(p,'DELETE',1)).status).toBe(403);
 expect((await req(p,'PATCH',0,{...data,action:'edit',title:'Updated apartment',budget:6000})).status).toBe(200);
 expect((await (await req(p)).json() as any).title).toBe('Updated apartment');
 for(let i=0;i<2;i++)expect((await req(p+'/like','PUT',1)).status).toBe(200);
 expect((await (await req(p,'GET',1)).json() as any).likeCount).toBe(1);
 expect((await req(p+'/comments','POST',1,{body:' '})).status).toBe(400);
 expect((await req(p+'/comments','POST',1,{body:'<img src=x onerror=alert(1)>'})).status).toBe(201);
 const comments:any=await (await req(p+'/comments','GET',0)).json();expect(comments[0].userId).toBe(users[1].id);expect(comments[0].body).toContain('<img');
 expect((await app.request('/v1'+p+'/like',{method:'PUT'},env)).status).toBe(401);
 await req(p+'/like','DELETE',1);expect((await (await req(p)).json() as any).likeCount).toBe(0);
 expect((await req(p,'DELETE',2)).status).toBe(200);
 for(const suffix of ['','/comments'])expect((await req(p+suffix,'GET',0)).status).toBe(404);
 expect((await req(p+'/like','PUT',1)).status).toBe(404);
 expect((await req(p+'/comments','POST',1,{body:'hidden'})).status).toBe(404);
 expect((await req(p,'PATCH',0,{...data,action:'edit'})).status).toBe(404);
 expect(await (await req('/community/inspections')).json()).toEqual([]);
 expect(db.prepare("SELECT COUNT(*) AS n FROM audit_logs WHERE action='marketplace.delete'").get()!.n).toBe(1);
 const second:any=await (await req('/community/inspections','POST',0,data)).json();expect((await req('/community/inspections/'+second.id,'DELETE',0)).status).toBe(200);
});
