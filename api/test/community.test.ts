import {it,expect} from 'vitest';
import {generateKeyPair,SignJWT} from 'jose';
import {createApp} from '../src/index';
import {makeD1} from './helpers/d1';

it('keeps chats private, contacts idempotent, and inspection transitions restricted to participants',async()=>{
 const {publicKey,privateKey}=await generateKeyPair('RS256'),{d1,db}=makeD1(),app=createApp(()=>publicKey);
 const env={DB:d1,ENVIRONMENT:'production',CLERK_ISSUER:'https://clerk.example',CLERK_JWKS_URL:'unused',ALLOWED_ORIGINS:'https://lowoo.vercel.app'} as any;
 const token=async(sub:string)=>new SignJWT({azp:'https://lowoo.vercel.app'}).setProtectedHeader({alg:'RS256'}).setIssuer(env.CLERK_ISSUER).setSubject(sub).setIssuedAt().setExpirationTime('5m').sign(privateKey);
 const tokens=await Promise.all(['requester','provider','outsider'].map(token));
 const req=(path:string,method='GET',who=0,body?:unknown)=>app.request(path.startsWith('/v1')?path:'/v1/community'+path,{method,headers:{Authorization:'Bearer '+tokens[who],'Content-Type':'application/json'},...(body!==undefined?{body:JSON.stringify(body)}:{})},env);
 const users:any[]=[];for(let i=0;i<3;i++)users.push(await (await req('/v1/me','GET',i)).json());
 const [a,b,z]=users.map(u=>u.id);
 expect((await app.request('/v1/community/users',{},env)).status).toBe(401);
 expect((await req('/users/'+a+'/contact','PUT')).status).toBe(400);
 for(let i=0;i<2;i++)expect((await req('/users/'+b+'/contact','PUT')).status).toBe(200);
 expect((await (await req('/users/'+b)).json() as any).followersCount).toBe(1);
 expect((await (await req('/v1/me')).json() as any).followingCount).toBe(1);
 for(let i=0;i<2;i++)await req('/users/'+b+'/contact','DELETE');
 expect((await (await req('/users/'+b)).json() as any).followersCount).toBe(0);
 const c:any=await (await req('/conversations','POST',0,{userId:b})).json();
 expect((await (await req('/conversations','POST',1,{userId:a})).json() as any).id).toBe(c.id);
 expect((await req('/conversations','POST',0,{userId:a})).status).toBe(400);
 expect((await req('/conversations/'+c.id+'/messages','POST',2,{body:'steal'})).status).toBe(404);
 expect((await req('/conversations/'+c.id+'/messages','GET',2)).status).toBe(404);
 expect((await req('/conversations/'+c.id+'/messages','POST',0,{body:' '})).status).toBe(400);
 for(const [who,message] of [[0,'Hello <script>'],[1,'Available tomorrow']] as const)expect((await req('/conversations/'+c.id+'/messages','POST',who,{body:message})).status).toBe(201);
 const messages:any=await (await req('/conversations/'+c.id+'/messages','GET',1)).json();expect(messages).toHaveLength(2);expect(messages.some((m:any)=>m.body==='Hello <script>')).toBe(true);
 expect(await (await req('/conversations','GET',2)).json()).toEqual([]);
 const r:any=await (await req('/inspections','POST',0,{title:'Check apartment',area:'Lekki',details:'Check the water',budget:5000})).json();
 const path='/inspections/'+r.id;
 expect((await req(path+'/offer','POST',0,{})).status).toBe(400);
 expect((await req(path,'PATCH',1,{action:'assign',providerId:b})).status).toBe(409);
 expect((await req(path,'PATCH',0,{action:'assign',providerId:b})).status).toBe(409);
 expect((await req(path+'/offer','POST',1,{})).status).toBe(200);
 expect((await req(path,'PATCH',0,{action:'assign',providerId:b})).status).toBe(200);
 expect((await req(path,'GET',2)).status).toBe(404);
 expect((await req(path,'PATCH',2,{action:'submit',report:'fake'})).status).toBe(409);
 expect((await req(path,'PATCH',0,{action:'complete'})).status).toBe(409);
 expect((await req(path,'PATCH',1,{action:'submit',report:'Water works. Road access checked.'})).status).toBe(200);
 expect((await req(path,'PATCH',1,{action:'complete'})).status).toBe(409);
 expect((await req(path,'PATCH',0,{action:'complete'})).status).toBe(200);
 expect((await req(path,'PATCH',0,{action:'cancel'})).status).toBe(409);
 expect((await (await req(path)).json() as any).status).toBe('completed');
 expect((await req('/inspections','POST',0,{title:'X',area:'Y',details:'Z',budget:-1})).status).toBe(400);
 db.prepare("UPDATE users SET status='suspended' WHERE id=?").run(z);
 expect((await req('/users/'+z+'/contact','PUT')).status).toBe(404);
 expect((await req('/conversations','GET',2)).status).toBe(403);
});
